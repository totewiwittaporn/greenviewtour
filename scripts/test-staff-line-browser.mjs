// Browser + real Local Auth/D1. Only LINE's external service is simulated and explicitly labelled.
import assert from 'node:assert/strict'
import {createHmac,randomUUID} from 'node:crypto'
import {writeFile} from 'node:fs/promises'
import {setup} from './local-browser-runtime.mjs'
const qa=await setup({lineTest:true}),base='http://localhost:5174',lineUserId='U'+'a'.repeat(32)
const email='staff-line-browser-'+Date.now()+'@example.test',password='Local-Staff-Line-Browser-12345'
let page,redirect
async function operator(name,data){
 const response=await fetch('http://127.0.0.1:8787/__audit/'+name,{method:'POST',headers:{'x-greenview-audit':qa.audit,'content-type':'application/json'},body:JSON.stringify(data),signal:AbortSignal.timeout(10000)})
 assert.equal(response.status,200);return response.json()
}
async function webhook(event){
 const body=JSON.stringify({destination:'U'+'0'.repeat(32),events:[event]})
 const response=await fetch('http://127.0.0.1:8787/api/line/staff/webhook',{method:'POST',headers:{'content-type':'application/json','x-line-signature':createHmac('sha256',qa.audit).update(body).digest('base64')},body,signal:AbortSignal.timeout(10000)})
 assert.equal(response.status,200)
}
try{
 await operator('seed',{email,password})
 await webhook({type:'message',mode:'active',webhookEventId:randomUUID(),timestamp:Date.now(),source:{type:'user',userId:lineUserId},replyToken:'fixture-reply',message:{id:randomUUID(),type:'text',text:'LINK STAFF'}})
 const {replies}=await operator('line-replies',{})
 const link=replies.at(-1).messages[0].text.split('\n').at(-1)
 page=await qa.page()
 await page.route('https://access.line.me/dialog/bot/accountLink?*',route=>{redirect=new URL(route.request().url());return route.fulfill({contentType:'text/html',body:'<h1>Local LINE verification fixture</h1>'})})
 await page.goto(link)
 await page.getByRole('heading',{name:'Staff sign in',exact:true}).waitFor()
 assert.equal(new URL(page.url()).hash,'')
 await page.getByLabel('Email address',{exact:true}).fill(email)
 await page.getByLabel('Current password',{exact:true}).fill(password)
 await page.getByRole('button',{name:'Sign in',exact:true}).click()
 await page.getByText('Local LINE test account',{exact:true}).waitFor()
 await qa.capture(page,'staff-line-consent-desktop')
 await page.getByRole('button',{name:'Confirm and continue to LINE',exact:true}).click()
 await page.getByRole('alert').getByText('Enter your password and accept the account-linking confirmation.',{exact:true}).waitFor()
 await page.getByLabel('Current password',{exact:true}).fill('incorrect-password')
 await page.getByRole('checkbox').check()
 await page.getByRole('button',{name:'Confirm and continue to LINE',exact:true}).click()
 await page.getByText('The password is incorrect. Please try again.',{exact:true}).waitFor()
 await page.getByLabel('Current password',{exact:true}).fill(password)
 await page.getByRole('button',{name:'Confirm and continue to LINE',exact:true}).click()
 await page.getByRole('heading',{name:'Local LINE verification fixture',exact:true}).waitFor()
 assert.ok(redirect)
 await webhook({type:'accountLink',mode:'active',webhookEventId:randomUUID(),timestamp:Date.now(),source:{type:'user',userId:lineUserId},link:{result:'ok',nonce:redirect.searchParams.get('nonce')}})
 await page.goto(base+'/profile')
 const card=page.locator('.staff-line-card')
 await card.locator('[data-status="LINKED"]').waitFor()
 await card.getByText('Local test only — not a real LINE connection',{exact:true}).waitFor()
 await qa.capture(page,'staff-line-linked-desktop')
 await page.setViewportSize({width:390,height:844});await card.scrollIntoViewIfNeeded();await qa.capture(page,'staff-line-linked-mobile')
 await page.evaluate(()=>window.dispatchEvent(new CustomEvent('greenview:locale',{detail:'th'})))
 await card.getByRole('heading',{name:'เชื่อมบัญชี LINE พนักงาน',exact:true}).waitFor()
 await card.getByText('ทดสอบบน Local เท่านั้น — ไม่ใช่การเชื่อม LINE จริง',{exact:true}).waitFor()
 await qa.capture(page,'staff-line-linked-thai-mobile')
 await card.getByRole('button',{name:'เชื่อมบัญชี LINE',exact:true}).click()
 await page.getByRole('dialog').waitFor()
 await page.getByRole('dialog').getByRole('button',{name:'ปิด',exact:true}).click()
 await page.evaluate(()=>window.dispatchEvent(new CustomEvent('greenview:locale',{detail:'en'})))
 await page.setViewportSize({width:1440,height:1000})
 await qa.mark('Real Local staff sign-in, consent, password recheck and signed LINE-fixture callback link only the current employee')
 const name=page.getByLabel('Display name',{exact:true}),original=await name.inputValue()
 await name.fill(original+' edit');assert.equal(await card.getByRole('button',{name:'Unlink LINE',exact:true}).isDisabled(),true)
 await page.getByRole('button',{name:'Discard changes',exact:true}).click()
 await card.getByRole('button',{name:'Unlink LINE',exact:true}).click()
 await page.getByRole('dialog').getByRole('button',{name:'Keep connection',exact:true}).click()
 assert.equal(await card.locator('[data-status="LINKED"]').count(),1)
 await card.getByRole('button',{name:'Unlink LINE',exact:true}).click()
 await page.getByRole('dialog').getByRole('button',{name:'Unlink LINE',exact:true}).click()
 await card.locator('[data-status="UNLINKED"]').waitFor()
 await page.reload();await card.locator('[data-status="UNLINKED"]').waitFor()
 await qa.capture(page,'staff-line-unlinked')
 await qa.mark('Profile edits remain protected; unlink requires confirmation and persists after reload without changing the staff account')
 await page.goto(link)
 await page.getByText('This link is invalid, expired or already used. Send “LINK STAFF” to the OA for a new link.',{exact:true}).waitFor()
 assert.equal(await page.getByRole('button',{name:'Confirm and continue to LINE',exact:true}).count(),0)
 await qa.mark('Consumed link cannot reopen a valid account-linking form')
 assert.deepEqual(qa.errors,[])
 assert.deepEqual(qa.responses.filter(response=>response.status>=500),[])
 const unexpected=qa.console.filter(row=>!row.text.includes('ERR_BLOCKED_BY_CLIENT')&&!/^Failed to load resource: the server responded with a status of (400|401) /.test(row.text))
 assert.deepEqual(unexpected,[])
 qa.status='PASS';await qa.save()
}catch(error){
 qa.status='FAIL';process.exitCode=1
 const message=error.message.replace(/https?:\/\/[^\s]+/g,'[URL REDACTED]')
 await writeFile(qa.directory+'/failure.json',JSON.stringify({name:error.name,message}),{mode:0o600})
 await page?.screenshot({path:qa.directory+'/failure.png'}).catch(()=>{})
 console.error('STAFF_LINE_BROWSER_FAILED',message)
}finally{await qa.close();console.log('STAFF_LINE_BROWSER',qa.status,'EVIDENCE='+qa.directory)}
